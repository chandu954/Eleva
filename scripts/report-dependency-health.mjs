#!/usr/bin/env node
/**
 * Dependency health report.
 *
 * Surfaces the metrics this repo previously only asserted in prose:
 *
 *   - total_transitive_deps   (count of resolved packages in pnpm-lock.yaml)
 *   - the direct runtime / dev split
 *   - majors held back on purpose, each with the constraint that blocks the bump
 *
 * It is *reporting*, not gating: the numbers land in the CI job summary and in
 * docs/DEPENDENCIES.md so a reviewer can see the real supply-chain surface
 * instead of taking the README's word for it. Blocking decisions stay with
 * `pnpm audit --audit-level=high` (advisories) and the overrides policy in
 * CONTRIBUTING.md.
 *
 * Usage: node scripts/report-dependency-health.mjs [--write]
 *   --write  also refresh docs/DEPENDENCIES.md
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const WRITE = process.argv.includes('--write');

const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
const lock = readFileSync(join(ROOT, 'pnpm-lock.yaml'), 'utf8');

const directRuntime = Object.keys(pkg.dependencies ?? {}).length;
const directDev = Object.keys(pkg.devDependencies ?? {}).length;

/**
 * Lockfile v9 keys the resolved set under the top-level "packages:" block as
 * two-space-indented `'name@version[(peer)(peer)]':` entries. Read exactly the
 * same subset awk would: start at "packages:", stop at the next top-level key.
 * Peer-suffixed duplicates collapse onto one name@version, and nested
 * "resolution"/"dependencies" maps are four-space indented, so the exact-depth
 * match skips them.
 */
function resolvedPackages() {
  const lines = lock.split('\n');
  const start = lines.indexOf('packages:');
  if (start === -1) throw new Error('pnpm-lock.yaml has no top-level "packages:" block');
  const names = new Set();
  for (const line of lines.slice(start + 1)) {
    if (line && !/^[ \t]/.test(line)) break; // next top-level key ends the block
    const match = line.match(/^  (?:"([^"]+)"|'([^']+)'|([^#:]+)):\s*$/);
    if (!match) continue;
    const raw = (match[1] ?? match[2] ?? match[3]).trim();
    const base = raw.replace(/\(.*\)$/, '').trim(); // strip peer-resolution suffix
    const at = base.lastIndexOf('@');
    if (at <= 0) continue; // not name@version
    const version = base.slice(at + 1);
    if (!/^\d/.test(version)) continue; // skip aliases / non-semver nodes
    names.add(`${base.slice(0, at)}@${version}`);
  }
  return names;
}

const resolved = resolvedPackages();
const transitive = Math.max(resolved.size - directRuntime - directDev, 0);

/**
 * Majors deliberately held back, with the constraint that blocks the bump.
 * Keep this aligned with the overrides block in pnpm-workspace.yaml.
 *
 * Registry-checked 2025-10-29: @stripe/stripe-js and @stripe/react-stripe-js
 * sat on 5.x/3.x only because react-stripe-js 3.x peer-locked stripe-js to
 * `<8.0.0`. Both are now on their latest majors (10.2.0 / 7.0.1, whose peer
 * range is `>=10.0.0 <11.0.0`), so they no longer belong in this list.
 */
const LAG_REASONS = {
  zod:
    'Pinned to 3.25.76 for the `zod/v3` subpath that `ai` and ' +
    'zod-to-json-schema import; the v4 migration is tracked separately.',
  '@opentelemetry/api':
    'Aligned to the OTel SDK 0.300 train, which needs >=1.10 for the `logs` ' +
    'export; the older resolved api broke `next build`.',
};

function escapeRe(str) {
  return str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * A held-back package may be a runtime dep, a dev dep, or present only through
 * a workspace override. Find the version actually recorded in the lockfile:
 * first from an importer's specifier/version pair, then from the packages keys.
 */
function lockedVersion(name) {
  const scoped = escapeRe(name);
  const importer = lock.match(
    new RegExp(`['"]?${scoped}['"]?:\\n\\s+specifier: \\S+\\n\\s+version: (\\S+)`),
  );
  if (importer) return importer[1].replace(/\(.*\)$/, '');
  const pkgKey = lock.match(new RegExp(`^  ['"]?${scoped}@([^'":(\\s]+)['"]?:`, 'm'));
  return pkgKey ? pkgKey[1] : 'unknown';
}

const heldBack = Object.entries(LAG_REASONS).map(([name, reason]) => {
  const all = { ...(pkg.dependencies ?? {}), ...(pkg.devDependencies ?? {}) };
  return {
    name,
    declared: all[name] ?? 'workspace override',
    version: lockedVersion(name),
    reason,
  };
});

const lines = [
  '# Dependency health',
  '',
  '_Generated by `node scripts/report-dependency-health.mjs --write`._',
  '_CI publishes the same numbers in the job summary. This file reports; it does',
  'not gate — advisories are enforced by `pnpm audit --audit-level=high` and the_',
  '_overrides policy in CONTRIBUTING.md._',
  '',
  '## Supply-chain surface',
  '',
  '| Metric | Value |',
  '| --- | --- |',
  `| Direct runtime dependencies | ${directRuntime} |`,
  `| Direct dev dependencies | ${directDev} |`,
  `| Resolved packages in pnpm-lock.yaml | ${resolved.size} |`,
  `| total_transitive_deps | ${transitive} |`,
  '',
  '## Majors held back deliberately',
  '',
  'Each entry names the constraint that currently blocks a bump. Revisit when',
  'upstream ships a compatible line.',
  '',
];

if (heldBack.length === 0) {
  lines.push('_None._', '');
} else {
  for (const row of heldBack) {
    lines.push(
      `- **${row.name}** — declared \`${row.declared}\`, locked \`${row.version}\``,
      `  ${row.reason}`,
      '',
    );
  }
}

lines.push(
  '## Keeping it current',
  '',
  '- `pnpm-workspace.yaml` → `auditConfig.ignoreGhsas` lists accepted advisories;',
  '  every entry needs a justification comment and a quarterly review.',
  '- Dependabot (`.github/dependabot.yml`) opens updates for direct dependencies.',
  '- `pnpm outdated` shows the full lag list against the registry.',
  '',
);

const text = lines.join('\n');

if (WRITE) {
  const dir = join(ROOT, 'docs');
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'DEPENDENCIES.md'), text);
}

// Surface the same table in the Actions run summary when running under CI.
if (process.env.GITHUB_STEP_SUMMARY) {
  writeFileSync(process.env.GITHUB_STEP_SUMMARY, text, { flag: 'a' });
}

console.log(
  `dependency-health: ${directRuntime} runtime + ${directDev} dev direct, ` +
    `${resolved.size} resolved (${transitive} transitive)` +
    `${WRITE ? ' — wrote docs/DEPENDENCIES.md' : ''}`,
);
